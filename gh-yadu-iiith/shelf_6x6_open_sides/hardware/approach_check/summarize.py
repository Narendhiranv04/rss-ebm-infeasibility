"""results.jsonl -> results.csv + summary.md (tables and 6x6 maps).  python3 summarize.py"""
import collections
import csv
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
R = [json.loads(line) for line in open(HERE / "results.jsonl")]
CLR_OK = 10.0                                            # mm a real robot needs


def ok(r):                                               # pickable: planned, lifted, held through the pull-back, nothing knocked
    return r["planned"] and r["lifted"] and r["held_after_retreat"] and not r["knocked"]


cols = ["gripper", "azset", "obj", "layout", "nbr", "row", "col", "n_neighbours", "planned", "fail_reason", "azimuth", "grasp_level",
        "branch", "teacher_rule", "lifted", "held_after_retreat", "knocked", "knock_phase", "max_disp_mm", "max_tilt_deg",
        "min_clear_mm", "min_clear_hand_mm", "min_clear_body", "min_clear_phase", "min_clear_target_mm", "contact", "pickable", "sec"]
with open(HERE / "results.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(cols)
    for r in R:
        row = {**r, "row": r["cell"][0], "col": r["cell"][1], "pickable": ok(r),
               "max_disp_mm": max(r.get("max_disp_mm", {}).values(), default=""), "max_tilt_deg": max(r.get("max_tilt_deg", {}).values(), default=""),
               "knocked": "+".join(r.get("knocked", [])), "contact": "+".join(r.get("contact", []))}
        w.writerow([row.get(c, "") for c in cols])

out = ["| gripper | approach | object | layout | nbr | pickable/tested | planned | lifted+held | knocked | contact | clr median mm | clr p5 mm | clr<10mm | main failure |",
       "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
groups = collections.defaultdict(list)
for r in R:
    groups[(r["gripper"], r["azset"], r["obj"], r["layout"], r["nbr"])].append(r)
for k, rs in sorted(groups.items()):
    pl = [r for r in rs if r["planned"]]
    c = [r["min_clear_mm"] for r in pl if r.get("min_clear_mm") is not None]
    fails = collections.Counter(r["fail_reason"] for r in rs if not r["planned"])
    fails.update("not lifted/held" for r in pl if not (r["lifted"] and r["held_after_retreat"]))
    out.append("| " + " | ".join(map(str, [*k, f"{sum(map(ok, rs))}/{len(rs)}", len(pl), sum(r["lifted"] and r["held_after_retreat"] for r in pl),
               sum(bool(r["knocked"]) for r in pl), sum(bool(r["contact"]) for r in pl),
               f"{np.median(c):.1f}" if c else "-", f"{np.percentile(c, 5):.1f}" if c else "-", sum(x < CLR_OK for x in c) if c else "-",
               "; ".join(f"{n} {v}" for v, n in fails.most_common(3)) or "-"])) + " |")

# 6x6 maps, approach set A: O pickable (clearance >= 10 mm or no neighbours), o pickable but clearance < 10 mm, K knocked,
# L planned but not lifted / dropped, x no plan, . not tested.  Row 5 (far) on top, row 0 (next to the robot) at the bottom.
maps = []
for k, rs in sorted(groups.items()):
    if k[1] != "A":
        continue
    cell = {tuple(r["cell"]): r for r in rs}
    lines = [f"{' / '.join(k)}   ({sum(map(ok, rs))}/{len(rs)} pickable)", "        c0 c1 c2 c3 c4 c5   (c0 = robot's right, -y)"]
    for row in range(5, -1, -1):
        s = []
        for col in range(6):
            r = cell.get((row, col))
            if r is None:
                s.append(".")
            elif not r["planned"]:
                s.append("x")
            elif r["knocked"]:
                s.append("K")
            elif not (r["lifted"] and r["held_after_retreat"]):
                s.append("L")
            else:
                s.append("o" if (r.get("min_clear_mm") is not None and r["min_clear_mm"] < CLR_OK) else "O")
        lines.append(f"  row {row}  " + "  ".join(s))
    lines.append("        (robot)")
    maps.append("\n".join(lines))
(HERE / "summary.md").write_text("# approach_check summary (generated by summarize.py)\n\n" + "\n".join(out) +
                                 "\n\n## 6x6 maps, approach set A (azimuth 180 only)\n\nO pickable, clearance >= 10 mm (or no neighbours); "
                                 "o pickable but clearance < 10 mm; K neighbour knocked; L not lifted / dropped; x no plan; . not tested\n\n```\n"
                                 + "\n\n".join(maps) + "\n```\n")
print("\n".join(out))
